import 'package:flutter_test/flutter_test.dart';
import 'package:michi/domain/japanese/dictionary_text.dart';

void main() {
  test('разворачивает известные сокращения', () {
    expect(cleanSense('(прост.) грубо'), '(просторечное) грубо');
    expect(cleanSense('(межд.) о, какой'), '(междометие) о, какой');
    expect(cleanSense('((англ.) coffee) кофе'), '((английское) coffee) кофе');
  });

  test('составные пометки разворачиваются все разом (реальный формат из словаря)', () {
    expect(
      cleanSense('(кн. суф. деепр. наст. вр.) текст'),
      '(книжное суффикс деепричастие настоящее время) текст',
    );
  });

  test('снимает сырую нумерацию источника', () {
    expect(cleanSense('1) первое значение'), 'первое значение');
    expect(cleanSense('2): второе значение'), 'второе значение');
  });

  test('неизвестные токены остаются как есть', () {
    expect(cleanSense('обычный текст без пометок'), 'обычный текст без пометок');
  });

  test('пров./преф. — реальный кейс из карточки かい (было замечено пользователем)', () {
    expect(
      cleanSense('(ист. пров.) Каи (соответствует преф. Яманаси)'),
      '(историческое провинция) Каи (соответствует префектура Яманаси)',
    );
  });

  test('счётный суффикс разворачивается полностью, а не только "суф."', () {
    expect(
      cleanSense('(счётный суф. для деревьев)'),
      '(счётный суффикс для деревьев)',
    );
  });

  test('parseMeaningsJson корректно бьёт по элементам массива, не по запятым', () {
    final list = parseMeaningsJson('["человек, люди","личность, характер"]');
    expect(list, ['человек, люди', 'личность, характер']);
  });

  test('primaryCleanMeaning берёт только первый смысл', () {
    expect(primaryCleanMeaning('["1) первое","2) второе"]'), 'первое');
  });
}
