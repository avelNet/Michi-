/// Правильный разбор JSON-массива — значения сами часто содержат запятую
/// внутри одного смысла ("человек, люди"), наивный split(',') резал бы
/// их на лишние куски.
List<String> parseMeaningsJson(String jsonArray) {
  final decoded = jsonDecode(jsonArray) as List;
  return decoded.map((e) => e.toString()).where((s) => s.isNotEmpty).toList();
}

/// Убирает сырую нумерацию источника ("1) ", "2): ") — список на экране
/// и так нумерует смыслы визуально — и разворачивает словарные
/// сокращения в читаемые слова: "(прост.)" → "(просторечное)".
String cleanSense(String raw) {
  var text = raw.replaceFirst(RegExp(r'^\d+\)\s*:?\s*'), '');
  text = text.replaceAllMapped(
    RegExp(r'([а-яёA-Za-zА-ЯЁ]+)\.'),
    (m) {
      final key = m.group(1)!.toLowerCase();
      final expansion = _abbreviations[key];
      return expansion ?? m.group(0)!;
    },
  );
  return text;
}

/// Только первый (основной) смысл, очищенный — для контекста, где места
/// мало (карточки повторения/урока): полный список см. cleanSense +
/// parseMeaningsJson по отдельности.
String primaryCleanMeaning(String jsonArray) {
  final list = parseMeaningsJson(jsonArray);
  if (list.isEmpty) return '';
  return cleanSense(list.first);
}

String joinCleanMeanings(String jsonArray) {
  return parseMeaningsJson(jsonArray).map(cleanSense).join(', ');
}
